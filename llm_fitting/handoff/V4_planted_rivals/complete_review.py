"""Audit the completed, unchanged V4 grid and tabulate the full seed evidence.

This post-run reporting helper does not change any generator, statistic,
classifier, prediction, threshold or adjudication. Run from the repo root.
"""
import gzip
import json
from collections import Counter
from datetime import datetime
from pathlib import Path
import sys
from zoneinfo import ZoneInfo

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "llm_fitting"))
from validation import balance_rivals_report as report
from validation import balance_rivals_study as study

OUT = ROOT / "llm_fitting/runs/2026-10-13_V4_planted_rivals"
HERE = Path(__file__).resolve().parent


def main():
    rows, missing = report.collect(OUT)
    assert len(rows) == 1200 and not missing
    assert all(r["status"] == "RAN-OK" for r in rows)
    audit = study.read(OUT / "audit.json")
    assert audit["sources"] == study.source_hashes()
    for name, digest in audit["tables"].items():
        assert study.digest(OUT / (name + ".csv.gz")) == digest
    with gzip.open(OUT / "seed_evidence.jsonl.gz", "rt") as f:
        for row in rows:
            assert json.loads(next(f)) == row
        assert not f.readline()
    attempts = sorted((OUT / "attempts").glob("*.json"))
    started = [p for p in attempts if not p.stem.endswith("_finished")]
    assert len(started) == 1200 and len(attempts) == 2400
    for p in started:
        assert study.read(p.with_name(p.stem + "_finished.json"))["status"] == "RAN-OK"
    with gzip.GzipFile(filename=str(OUT / "attempts.jsonl.gz"), mode="wb", mtime=0) as f:
        for p in attempts:
            f.write((json.dumps({"file": p.name, "record": study.read(p)}, sort_keys=True) + "\n").encode())
    ev = [r for r in rows if r["provenance"]["stage"] == "evaluation"]
    for r in ev:
        p = r["provenance"]
        forecast = study.read(OUT / "predictions" / p["panel"] / p["rival"] / (str(p["seed"]) + ".json"))
        assert forecast["provenance"] == p
        assert forecast["predictions"] == study.clean(study.slope_predictions(r["analysis"]))
    summary = dict(status="COMPLETE", terminal=1200, failed=0, started_attempts=1200,
                   finished_attempts=1200, unmatched_attempts=0, forecasts_verified=600,
                   source_input_population_and_table_checks="PASS", archive_equality="PASS",
                   first_attempt_JST=datetime.fromtimestamp(min(p.stat().st_mtime for p in started), ZoneInfo("Asia/Tokyo")).isoformat(),
                   last_cell_JST=datetime.fromtimestamp(max(p.stat().st_mtime for p in (OUT / "cells").rglob("*.json")), ZoneInfo("Asia/Tokyo")).isoformat(),
                   maximum_accounting_residual=max(r["scores"]["A1"]["detail"]["max_abs_resid"] for r in ev))
    study.write(OUT / "completion_audit.json", summary)
    old_progress = OUT / "progress.json"
    if old_progress.exists() and study.read(old_progress).get("status") == "IN PROGRESS":
        archive = OUT / "progress_before_completion.json"
        if not archive.exists():
            archive.write_bytes(old_progress.read_bytes())
    study.write(old_progress, dict(status="COMPLETE", completed=1200, expected=1200, missing=[], failed=[],
                                  note="Verified completed grid; see completion_audit.json. Prior snapshot retained."))
    lines = ["# V4 completion tables", "", "2026-10-14 · Exploratory synthetic validation; no empirical M1 output opened.", "",
             "Generated by `complete_review.py` from the full fixed grid. Rates are k/n with Wilson 95% intervals; continuous summaries are median [5th, 95th seed percentiles]. Each rival/profile has 20 evaluation seeds. Missing statistics retain their eligibility counts.", ""]
    def table(title, headers, vals):
        lines.extend(["## " + title, "", "| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)])
        lines.extend("| " + " | ".join(map(str, v)) + " |" for v in vals)
        lines.append("")
    def band(vals):
        x = np.array([v for v in vals if v is not None and np.isfinite(v)])
        return "NA (n=0)" if not len(x) else f"{np.median(x):.4g} [{np.quantile(x,.05):.4g}, {np.quantile(x,.95):.4g}] (n={len(x)})"
    def rate(k, n):
        w = report.wilson(k,n)
        return "NA (n=0)" if not n else f"{k}/{n} [{w['lo']:.3f}, {w['hi']:.3f}]"
    groups = {}
    for r in ev:
        p=r["provenance"]; groups.setdefault((p["panel"],p["rival"]),[]).append(r)
    signs, nuisance, bridges, errors, availability = [], [], [], [], []
    for (panel,rival), group in groups.items():
        neg, joint, contributions, br, raw, latent, reasons = [], [], [], {}, [], [], Counter()
        for r in group:
            pair=study.m1._pair(r["analysis"]["boundaries"]["1.0"],"primary")
            car=(pair or {}).get("carriers",{})
            if "pos_q95" in car and "home_q05" in car:
                neg.append(car["pos_q95"]<0); joint.append(car["pos_q95"]<0 and car["home_q05"]>0)
            if pair and "not_adjudicated" in pair: reasons[str(pair["not_adjudicated"])]+=1
            c=r["oracle"].get("contributions",[])
            if c: contributions.append(min(c,key=lambda v:abs(v["k"]-r["provenance"]["config"]["K"]/4)))
            for k,v in r["scores"]["B9"]["detail"].get("r_over_small_step",{}).items():
                br.setdefault(k,[]).append(v)
            v=[v.get("relative_error") for v in r["heldout"].values()]
            lv=[v.get("latent_relative_error") for v in r["heldout"].values()]
            if all(x is not None and np.isfinite(x) for x in v): raw.append(max(abs(x) for x in v))
            if all(x is not None and np.isfinite(x) for x in lv): latent.append(max(abs(x) for x in lv))
        signs.append([panel,rival,len(joint),rate(sum(neg),len(neg)),rate(sum(joint),len(joint)),rate(sum(r["scores"]["B3"]["status"]=="FAIL" for r in group),20)])
        nuisance.append([panel,rival,*[band([r.get(k) for r in contributions]) for k in ("nuisance_g","nuisance_fraction","nuisance_predictable_share")]])
        bridges.extend([panel,rival,k,band(v)] for k,v in sorted(br.items(),key=lambda kv:int(kv[0])))
        errors.append([panel,rival,band(raw),band(latent),20-len(raw)])
        if reasons: availability.append([panel,rival,str(dict(reasons))])
    table("Carrier signs and bin differences",["profile","rival","carrier eligible /20","negative position","joint restoring","B3 FAIL /20"],signs)
    table("Passing-layer loss at K/4",["profile","rival","nuisance g / endpoint-week","nuisance G/G (G>0)","predictable nuisance / R"],nuisance)
    table("Reordering gain / small-step value",["profile","rival","k","seed band"],bridges)
    table("Held-out error over all five boundaries",["profile","rival","maximum absolute observed relative error","maximum absolute latent relative error","invalid forecasts /20"],errors)
    table("Uncertified primary pairs",["profile","rival","reason counts /20"],availability)
    scores=pd.read_csv(OUT/"scores.csv.gz")
    counts=scores.groupby(["panel","prediction","status"]).size().unstack(fill_value=0)
    table("Every M1 item and screen (ten rivals pooled descriptively)",["profile","item",*counts.columns],[[*idx,*row] for idx,row in counts.iterrows()])
    matching=pd.read_csv(OUT/"marginal_matching.csv.gz")
    counts=matching.groupby(["panel","status"]).size().unstack(fill_value=0)
    table("Marginal comparison counts",["profile",*counts.columns],[[idx,*row] for idx,row in counts.iterrows()])
    coverage=pd.read_csv(OUT/"coverage.csv.gz")
    table("Coverage target precision",["profile","eligible seed/boundary targets","precise targets","median MC-band / interval width"],[[p,len(d),int(d.precise.sum()),float(np.median((d.target_hi-d.target_lo)/(d.hi-d.lo)))] for p,d in coverage.groupby("panel")])
    (HERE/"COMPLETION_TABLES.md").write_text("\n".join(lines).rstrip()+"\n")
    print(json.dumps(summary,indent=2))


if __name__ == "__main__":
    main()
